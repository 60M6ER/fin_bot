package ru.larionov.backend.exchange.api.enums;

/**
 * Сегмент рынка — «по каким правилам инструмент торгуется».
 *
 * Ортогонален {@link InstrumentKind}, который отвечает на другой вопрос — «что это за бумага».
 * Разводить их обязательно: фьючерс на акцию и сама акция имеют разный вид И разный сегмент,
 * а вот бессрочный своп и спот на криптобирже — одинаковый вид (CRYPTO) при разном сегменте.
 * Если бы ось была одна, вторая биржа потребовала бы миграции данных.
 *
 * PERPETUAL и MARGIN сейчас не используются ни одним адаптером — это задел под крипту,
 * где именно по этой оси биржи и делят свои рынки.
 */
public enum MarketSegment {
    SPOT,
    FUTURES,
    OPTIONS,
    PERPETUAL,
    MARGIN,
    OTHER
}

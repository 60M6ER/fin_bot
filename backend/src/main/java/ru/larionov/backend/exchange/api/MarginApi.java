package ru.larionov.backend.exchange.api;

import ru.larionov.backend.exchange.api.model.account.MarginAttributes;
import ru.larionov.backend.exchange.api.model.id.AccountId;

/**
 * Маржинальные показатели счёта.
 *
 * Отдельный интерфейс, а не метод на {@link AccountsApi}, потому что источник у него
 * есть не у всякой площадки: спотовая биржа непокрытых позиций не знает вовсе, и
 * возвращать оттуда выдуманные числа было бы хуже, чем не возвращать ничего.
 * Отсюда же {@code Optional} на {@link ExchangeClient#margin()} — та же форма, что
 * у стримов, которые тоже есть не везде.
 *
 * Разрешение торговать с плечом живёт не здесь: его даёт галка в подключении.
 * Это разные вопросы — «умеем ли мы спросить обеспечение» и «позволено ли им
 * рисковать», — и путать их нельзя. Площадка без этого интерфейса означает, что
 * спросить не у кого, и бот с включённой маржой обязан не стартовать, а не
 * торговать вслепую.
 */
public interface MarginApi {

    /**
     * @return показатели на момент запроса; никогда не null — отсутствие ответа
     *         это исключение, а не пустая структура с нулями
     */
    MarginAttributes getMarginAttributes(AccountId accountId);
}

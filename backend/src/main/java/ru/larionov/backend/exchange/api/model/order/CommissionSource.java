package ru.larionov.backend.exchange.api.model.order;

/**
 * Откуда пришло число комиссии.
 *
 * Биржи отдают комиссии по-разному: где-то факт приходит сразу с ордером, где-то
 * только после сверки, а стрим может вообще не содержать комиссию. Поэтому источник
 * хранится рядом с суммой и не зашивается в конкретный адаптер биржи.
 */
public enum CommissionSource {
    /** Фактическая комиссия, подтверждённая биржей по исполненному ордеру. */
    EXCHANGE_EXECUTED,
    /** Оценка/резерв комиссии, которую биржа вернула до окончательного исполнения. */
    EXCHANGE_INITIAL,
    /** Оценка, посчитанная нами по ставке тарифа, когда биржа ещё не дала сумму. */
    BROKER_RATE_ESTIMATE
}

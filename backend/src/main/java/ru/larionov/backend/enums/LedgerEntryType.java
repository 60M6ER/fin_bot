package ru.larionov.backend.enums;

public enum LedgerEntryType {
    TRADE_BUY(true),
    TRADE_SELL(true),
    COMMISSION_CORRECTION(true),
    CYCLE_RESULT(false),
    GRID_REPLACED(false),

    /**
     * Оператор изменил бюджет бота: доливка денег или их вывод.
     *
     * Денег не двигает — двигает РАМКУ: сколько бот вправе задействовать. Отметка
     * нужна, чтобы история «сколько в бота вложено» не врала: внешний взнос не
     * является прибылью и в P/L не попадает, а базу доходности сдвигает.
     */
    BUDGET_CHANGED(false),

    /**
     * Хвост закрытого цикла, который невозможно продать: мельче шага количества
     * либо дешевле минимальной суммы заявки.
     *
     * Денег не двигает — двигает УЧЁТ: количество и его себестоимость уходят из
     * партий сетки в отдельную корзину. У каждого хвоста своя цена, и усреднять
     * их с живой позицией нельзя: сетка считала бы занятым уровень, на котором
     * продавать нечего, а покупать не даёт эта же запись.
     *
     * Копится через поколения диапазона. Когда накопленного хватает на заявку,
     * которую биржа примет, оно уходит одной продажей — см. OrderPurpose.DUST.
     */
    DUST(false);

    private final boolean affectsCash;

    LedgerEntryType(boolean affectsCash) {
        this.affectsCash = affectsCash;
    }

    public boolean affectsCash() {
        return affectsCash;
    }
}

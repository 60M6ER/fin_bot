package ru.larionov.backend.enums;

/**
 * Зачем выставлен ордер.
 *
 * Раньше назначение выражалось косвенно — «продажа без уровня сетки значит
 * ликвидация». Договорённость держалась, пока не-сеточная заявка была ровно одна;
 * с появлением продажи пыли она сломалась бы молча: ликвидация нашла бы чужую
 * заявку и сняла её, приняв за свою.
 */
public enum OrderPurpose {

    /** Обычная заявка сетки: у неё есть уровень, и она живёт по правилам поколения. */
    GRID,

    /** Закрытие позиции по рынку перед перестановкой диапазона вниз. */
    LIQUIDATION,

    /**
     * Продажа накопленной пыли.
     *
     * Живёт отдельно от сетки и переживает перестановку диапазона: пыль копится
     * ЧЕРЕЗ поколения, и снимать её продажу вместе с сеткой значило бы начинать
     * накопление заново. Поэтому такая заявка исключена из проверок, которые
     * требуют «на бирже не осталось наших заявок».
     */
    DUST,

    /**
     * Переворот позиции с множителем: закрывает старую и открывает противоположную.
     *
     * Единственное назначение, которому разрешено провести позицию ЧЕРЕЗ НОЛЬ.
     * Обычная сетка такого делать не должна ни при каком стечении обстоятельств:
     * её продажа закрывает купленное, а не открывает долг. Проверка живёт в
     * риск-контроле, потому что обязана пережить любую ошибку стратегии.
     */
    HEDGE,

    /**
     * Закрытие восстановительного плеча по расчётной цене безубытка.
     *
     * Отдельно от {@link #GRID}, потому что живёт по своим правилам: у неё нет уровня,
     * она не участвует в проверках «на бирже не осталось заявок сетки», а её партии
     * нельзя смешивать с сеточными — иначе при одновременной работе закрытие плеча
     * съело бы себестоимость чужого цикла.
     */
    RECOVERY
}

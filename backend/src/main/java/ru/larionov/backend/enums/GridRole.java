package ru.larionov.backend.enums;

/**
 * Роль заявки в цикле уровня: открывает она экспозицию или закрывает.
 *
 * Пока сетка была только лонговой, роль выводилась из стороны: покупка открывает,
 * продажа закрывает. С появлением шорта сторона перестаёт отвечать на этот вопрос —
 * там всё ровно наоборот, — а от ответа зависят три вещи сразу: занят ли уровень,
 * открывает ли сделка партию в денежной книге и что считать встречной заявкой.
 *
 * Это та же история, что с {@link OrderPurpose}: договорённость «продажа без уровня
 * значит ликвидация» держалась, пока не-сеточная заявка была ровно одна, и сломалась
 * бы молча со второй. «Покупка значит открытие» — договорённость того же сорта,
 * и ломается она ровно сейчас.
 *
 * Хранится в БД, а не выводится на лету, потому что читателю роль нужна там, где
 * направления под рукой нет: риск-контроль сравнивает намерение с уже лежащими
 * в журнале заявками, а денежная книга восстанавливает партии по строкам, которые
 * писали РАЗНЫЕ поколения с разным направлением. Вывести роль из текущего
 * направления задним числом означало бы переписать историю при первом же перевороте.
 */
public enum GridRole {

    /** Заявка набирает позицию: покупка в лонге, продажа в шорте. */
    OPEN,

    /**
     * Заявка закрывает набранное: продажа в лонге, покупка в шорте.
     *
     * Сюда же относятся ликвидация и продажа пыли — они закрывают позицию,
     * пусть и не по правилам уровня.
     */
    CLOSE
}

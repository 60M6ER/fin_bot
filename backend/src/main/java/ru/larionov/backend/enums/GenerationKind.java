package ru.larionov.backend.enums;

/**
 * Что описывает строка в таблице поколений.
 *
 * Раньше строка всегда означала диапазон сетки, и вид был не нужен. С появлением
 * восстановительного плеча в таблице появился второй род отрезков: у него нет
 * диапазона и уровней, зато есть цена входа, цель и собственный результат.
 * Показывать их одной строкой нельзя — это разные события с разными деньгами.
 */
public enum GenerationKind {

    /** Поколение сетки: диапазон от постановки до перестановки. */
    GRID,

    /**
     * Восстановительный эпизод: позиция переложена в плечо и ждёт откупа.
     *
     * Живёт параллельно поколению сетки, а не вместо него, поэтому его окно
     * в книге пересекается с сеточным, и деньги разделяются по назначению заявок.
     */
    RECOVERY
}

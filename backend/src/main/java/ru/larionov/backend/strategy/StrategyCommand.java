package ru.larionov.backend.strategy;

/**
 * Ручное вмешательство оператора в работу стратегии.
 *
 * Отдельно от рыночных событий, потому что это единственный вид входа, у которого
 * есть автор: решение принял человек, и стратегия вправе снять ради него защиту,
 * которую сама себе не отключила бы никогда.
 */
public enum StrategyCommand {

    /**
     * Закрыть позицию по рынку, зафиксировать убыток и построить сетку заново
     * вокруг текущей цены.
     *
     * Существует ради тупика, в который сетка попадает штатно: после исчерпания
     * бюджета убытка автоматическая перестановка вниз запрещена навсегда, а цена
     * ушла настолько ниже диапазона, что бот не может ни купить (уровни выше цены),
     * ни продать (позиция куплена дороже). Бот при этом формально работает, но
     * не делает ничего и вернуться в строй сам не может.
     */
    FORCE_GRID_REPLACEMENT("перестройка сетки с фиксацией убытка",
            "GRID-боту с автоматическим диапазоном"),

    /**
     * Плановая остановка: снять покупки и дождаться, пока распродастся позиция.
     *
     * Обычная остановка гасит бота там, где он есть, — вместе с купленной, но ещё
     * не проданной позицией. Она никуда не денется и останется на счёте, а бота
     * после этого нельзя даже удалить, не разобравшись с ней руками.
     *
     * Плановая делает то же самое, но в правильном порядке: покупки прекращаются
     * сразу, встречные продажи продолжают работать, и бот выключается сам, когда
     * продавать станет нечего. Позиция закрывается по СВОИМ ценам сетки, а не по рынку,
     * поэтому ждать может долго — это осознанный размен: цена вместо скорости.
     */
    SCHEDULE_STOP("плановая остановка", "GRID-боту"),

    /**
     * Передумали: вернуть бота в обычную работу.
     *
     * Без этой команды плановая остановка была бы ловушкой — решение, принятое
     * на час, отменялось бы только полной остановкой бота, то есть ровно тем,
     * чего плановая и позволяет избежать.
     */
    CANCEL_SCHEDULED_STOP("отмена плановой остановки", "GRID-боту");

    private final String title;
    private final String availableTo;

    StrategyCommand(String title, String availableTo) {
        this.title = title;
        this.availableTo = availableTo;
    }

    /** Название для человека: отказ в выполнении читает оператор, а не разработчик. */
    public String title() {
        return title;
    }

    /**
     * Кому команда доступна. Хранится рядом с самой командой, чтобы отказ называл
     * ту команду, которую действительно отклонили: раньше текст отказа был один на
     * всех и сообщал про перестройку сетки в ответ на любое нажатие.
     */
    public String availableTo() {
        return availableTo;
    }
}

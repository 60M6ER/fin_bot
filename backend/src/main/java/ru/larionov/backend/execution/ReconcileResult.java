package ru.larionov.backend.execution;

import java.math.BigDecimal;
import java.util.List;

/**
 * Итог сверки с биржей.
 *
 * <h3>Две разные позиции, и путать их дорого</h3>
 * Счёт на бирже общий: на нём лежит и остаток прошлой жизни бота, и монеты соседнего
 * бота на том же инструменте, и то, что владелец купил руками. Своей боту принадлежит
 * только та часть, которую он сам купил и записал в журнал.
 *
 * Пока это была одна величина, «позицией бота» служил ВЕСЬ остаток счёта. Отсюда
 * следовало три неверных вывода подряд: новый бот с пустым журналом считал чужой
 * остаток своим и отказывался стартовать; сверка бесконечно сообщала о расхождении,
 * которого нет; а принудительная ликвидация выставляла на продажу весь остаток —
 * то есть чужие монеты.
 *
 * @param openOrders       ордера, живые на бирже после сверки
 * @param position         позиция БОТА по его журналу — единственное, чем он вправе
 *                         распоряжаться
 * @param exchangePosition весь остаток счёта по инструменту, включая чужое
 * @param usedCapital      деньги, занятые активными заявками и позицией
 * @param resolvedPending  сколько «повисших» записей удалось дорешить
 * @param adoptedOrphans   сколько ордеров нашлось на бирже, но отсутствовало в журнале
 * @param positionMismatch остаток счёта минус позиция журнала. ОТРИЦАТЕЛЬНОЕ значение —
 *                         беда: журнал считает, что бот владеет тем, чего на счёте нет,
 *                         и встречные продажи окажутся необеспеченными. Положительное
 *                         означает лишь, что на счёте есть чужое, — это норма
 */
public record ReconcileResult(
        List<BotOrderView> openOrders,
        BigDecimal position,
        BigDecimal exchangePosition,
        BigDecimal usedCapital,
        int resolvedPending,
        int adoptedOrphans,
        BigDecimal positionMismatch
) {

    /**
     * Недостача: на счёте меньше, чем числится за ботом.
     *
     * Проверяется только эта сторона. Излишек на счёте — чужие монеты, и запрещать
     * из-за них торговлю значит запретить двум ботам жить на одном инструменте
     * и не пережить ни одной неторгуемой пылинки от прошлого цикла.
     */
    public boolean positionShortfall() {
        if (positionMismatch == null || position == null || exchangePosition == null) {
            return positionMismatch != null && positionMismatch.signum() < 0;
        }

        // Знаки разошлись — бот и биржа держат позицию в РАЗНЫЕ стороны. Хуже любой
        // недостачи: тут не «чего-то не хватает», а «мы не понимаем, чем владеем».
        if (position.signum() != 0 && exchangePosition.signum() != 0
                && position.signum() != exchangePosition.signum()) {
            return true;
        }

        // Дальше сравниваем ПО МОДУЛЮ. Прежнее правило «разница отрицательна» верно
        // только для длинной позиции: у короткой всё зеркально, и недостача выглядит
        // положительной разницей. Журнал −10 при биржевых −9 давал mismatch +1, что
        // читалось как «на счёте есть чужое, норма», хотя означало ровно обратное —
        // бот должен больше, чем должен на самом деле, и откуп окажется не тем.
        return exchangePosition.abs().compareTo(position.abs()) < 0;
    }

    public boolean hasFindings() {
        return resolvedPending > 0 || adoptedOrphans > 0 || positionShortfall();
    }
}

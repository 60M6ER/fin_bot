package ru.larionov.backend.money;

import java.util.Optional;

/**
 * Источник курса доллара к рублю.
 *
 * Пустой Optional — штатный ответ, а не ошибка: сеть могла не ответить, подключение
 * к брокеру могло быть погашено. Вызывающая сторона обязана уметь показать «курс
 * недоступен» вместо того, чтобы подставить ноль или прошлогоднее значение молча.
 */
public interface FxRateProvider {

    /** Идентификатор для настройки и для подписи под числом: CBR, T_INVEST. */
    String id();

    Optional<FxRate> usdRub();
}

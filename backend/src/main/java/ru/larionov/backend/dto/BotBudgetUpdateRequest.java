package ru.larionov.backend.dto;

import java.math.BigDecimal;

/**
 * Изменение бюджета бота — единственная настройка, которую можно менять на ходу.
 *
 * Узкий запрос, а не общий {@link BotUpdateRequest}: тот требует остановленного бота,
 * потому что меняет стратегию и подключение, под которые уже выставлены заявки.
 * Бюджет же не меняет ни диапазон, ни поколение, ни открытые циклы — только размер
 * будущих покупок, и ради доливки денег рвать работающие циклы незачем.
 *
 * @param budget      новый бюджет целиком. Заданная сумма, а не доля портфеля
 * @param addToBudget прибавка к нынешнему бюджету; отрицательная означает вывод.
 *                    Складывает СЕРВЕР, и это не придирка: в интерфейсе показан рабочий
 *                    бюджет, а он у бота с реинвестированием равен «бюджет плюс
 *                    реализованная прибыль». Прибавь клиент к нему — и прибыль тихо
 *                    осела бы в базовом бюджете, то есть перестала бы выводиться
 * @param maxCapital  потолок задействованных денег, если его нужно поднять вместе с
 *                    бюджетом. null — оставить прежним. Бюджет выше потолка бессмыслен:
 *                    сетка не сможет выкупить свои же уровни, и проверка это отвергнет
 */
public record BotBudgetUpdateRequest(
        BigDecimal budget,
        BigDecimal addToBudget,
        BigDecimal maxCapital
) {}
